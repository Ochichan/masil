//! Transparent external-terminal wrapper (`masil-agent wrap -- <cmd...>`).
//! Spawns the agent inside a masil server pane and attaches the current
//! terminal transparently so desktop tabs work normally while mobile stays
//! live-attached to the exact same PTY.

use crate::native_ui::native_executable;
use crate::remote::config::random_token_b64;
use crate::remote::discovery::default_masil_socket;
use std::os::unix::process::CommandExt;
use std::path::PathBuf;
use std::process::Command;

pub fn run(args: &[String]) -> Result<i32, String> {
    if args.is_empty()
        || matches!(
            args.first().map(String::as_str),
            Some("--help" | "-h" | "help")
        )
    {
        println!(
            "masil-agent wrap — run an agent command inside a transparent masil PTY\n\n\
             Usage:\n  \
               masil-agent wrap [--socket PATH] [--session NAME] [--name AGENT] -- COMMAND [ARGS...]\n  \
               masil-agent wrap init [zsh|bash|fish]\n\n\
             If already inside a masil pane, runs COMMAND directly without nesting."
        );
        return Ok(0);
    }

    if args[0] == "init" {
        let shell = args.get(1).map(String::as_str).unwrap_or("zsh");
        print_shell_init(shell)?;
        return Ok(0);
    }

    let mut socket: Option<PathBuf> = None;
    let mut session_name: Option<String> = None;
    let mut agent_name: Option<String> = None;
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--" => {
                i += 1;
                break;
            }
            "--socket" if i + 1 < args.len() => {
                socket = Some(PathBuf::from(&args[i + 1]));
                i += 2;
            }
            "--session" if i + 1 < args.len() => {
                session_name = Some(args[i + 1].clone());
                i += 2;
            }
            "--name" if i + 1 < args.len() => {
                agent_name = Some(args[i + 1].clone());
                i += 2;
            }
            _ => break,
        }
    }

    let cmd_args = &args[i..];
    if cmd_args.is_empty() {
        return Err("wrap requires a command after `--`".into());
    }

    // If already running inside a masil server pane, exec directly without nesting.
    if let Ok(tmux_env) = std::env::var("TMUX")
        && tmux_env.contains("masil-")
    {
        let err = Command::new(&cmd_args[0]).args(&cmd_args[1..]).exec();
        return Err(format!("exec {} failed: {err}", cmd_args[0]));
    }

    let masil = native_executable()?;
    let sock = match socket {
        Some(s) => s,
        None => default_masil_socket()?,
    };
    let cwd = std::env::current_dir().map_err(|e| format!("cannot read current directory: {e}"))?;
    let dir_label = cwd
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("work")
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '-' })
        .take(18)
        .collect::<String>();
    let short_id = random_token_b64(4)
        .to_ascii_lowercase()
        .replace(['-', '_'], "0");
    let session = session_name.unwrap_or_else(|| {
        format!(
            "wrap-{}-{}",
            dir_label.trim_matches('-'),
            &short_id[..6.min(short_id.len())]
        )
    });

    // Launch the command directly as the session's initial process (no shell quoting)
    // and attach immediately. When the command exits, the wrapped session ends cleanly.
    let mut c = Command::new(&masil);
    c.arg("-u")
        .arg("-S")
        .arg(&sock)
        .arg("new-session")
        .arg("-s")
        .arg(&session)
        .arg("-c")
        .arg(&cwd);
    if let Some(ref name) = agent_name {
        c.arg("-n").arg(name);
    }
    c.arg("--").args(cmd_args);

    let status = c
        .status()
        .map_err(|e| format!("failed launching wrapped masil session: {e}"))?;
    Ok(status.code().unwrap_or(1))
}

fn print_shell_init(shell: &str) -> Result<(), String> {
    let bin = std::env::current_exe()
        .ok()
        .map(|p| p.to_string_lossy().into_owned())
        .unwrap_or_else(|| "masil-agent".into());
    match shell {
        "zsh" | "bash" => {
            println!(
                r#"# masil external terminal wrappers (generated by `masil-agent wrap init {shell}`)
masil_wrap() {{ "{bin}" wrap -- "$@"; }}
for _masil_cmd in claude codex opencode agy; do
  eval "${{_masil_cmd}}() {{ \"{bin}\" wrap -- ${{_masil_cmd}} \"\$@\"; }}"
done
unset _masil_cmd"#
            );
            Ok(())
        }
        "fish" => {
            println!(
                r#"# masil external terminal wrappers (generated by `masil-agent wrap init fish`)
for _cmd in claude codex opencode agy
    function $_cmd --inherit-variable _cmd
        "{bin}" wrap -- $_cmd $argv
    end
end"#
            );
            Ok(())
        }
        other => Err(format!(
            "unsupported shell: {other} (use zsh, bash, or fish)"
        )),
    }
}
