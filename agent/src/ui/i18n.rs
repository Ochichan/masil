pub(crate) fn action_label(
    language: Language,
    action: Action,
    waiting: bool,
    expanded: bool,
) -> &'static str {
    let key = match action {
        Action::MarkSeen if waiting => Text::MarkingSeen,
        Action::MarkSeen => Text::MarkSeen,
        Action::GoToPane => Text::GoToPane,
        Action::Details => Text::Details,
        Action::CopyId => Text::CopyId,
        Action::Expand if expanded => Text::Restore,
        Action::Expand => Text::Expand,
        Action::Retry => Text::Retry,
    };
    tr(language, key)
}

