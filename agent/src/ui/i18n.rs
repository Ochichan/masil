pub(crate) fn action_label(
    language: Language,
    action: Action,
    waiting: bool,
    expanded: bool,
) -> &'static str {
    let key = match action {
        Action::MarkSeen if waiting => Text::MarkingSeen,
        Action::MarkSeen => Text::MarkSeen,
        Action::GoToPane => Text::GoToPane,
        Action::Details => Text::Details,
        Action::CopyId => Text::CopyId,
        Action::Expand if expanded => Text::Restore,
        Action::Expand => Text::Expand,
        Action::Retry => Text::Retry,
        Action::NewAgent => Text::NewAgent,
        Action::RenameAgent => Text::RenameAgent,
        Action::ResumeAgent => Text::ResumeAgent,
        Action::PrepareDraft => Text::PrepareDraft,
        Action::SendPrompt => Text::SendPrompt,
        Action::InterruptAgent => Text::InterruptAgent,
        Action::ReadScreen => Text::ReadScreen,
        Action::CloseAgent => Text::CloseAgent,
        Action::Answer => return word(language, "Answer requests", "요청에 답하기"),
        Action::Inbox => return word(language, "Inbox", "인박스"),
        Action::NextUnseen => return word(language, "Next unseen event", "다음 안 읽은 사건"),
    };
    tr(language, key)
}

